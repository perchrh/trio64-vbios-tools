# usage: python3 gen_vgaref.py <ROM image> <folder with VGATEST CRTC.COL GENERAL.COL DSTATE.COL>
# generates vgaref.inc from the ROM VGA parameter table and the IBM reference files (VGATEST)
import sys
A=(sys.argv[2] if len(sys.argv)>2 else '.')+'/'
rom=open(sys.argv[1] if len(sys.argv)>1 else 'S3V2P9.BIN','rb').read()
crt=open(A+'CRTC.COL','rb').read()
gen=open(A+'GENERAL.COL','rb').read()
dst=open(A+'DSTATE.COL','rb').read()
order=[0,1,2,3,4,5,6,7,0xd,0xe,0xf,0x10,0x11,0x12,0x13]
idx={0:0x17,1:0x17,2:0x18,3:0x18,4:4,5:5,6:6,0xd:0xd,0xe:0xe,0x10:0x12,0x11:0x1a,0x12:0x1b,0x13:0x1c}
# memtype 1 text(bytes) 2 cga(bytes) 3 planar 4 chain4 ; hz
info={0:(1,16384,70),1:(1,16384,70),2:(1,32768,70),3:(1,32768,70),4:(2,16384,70),5:(2,16384,70),6:(2,16384,70),
      0xd:(3,0,70),0xe:(3,0,70),0x10:(3,0,70),0x11:(3,0,60),0x12:(3,0,60),0x13:(4,65536,70)}
out=[]
out.append('; generated by gen.py: IBM reference (VGATEST .COL files) + ROM parameter table')
out.append('VGAN equ %d'%len(idx))
out.append('vgaref:')
for n,m in enumerate(order):
    if m not in idx: continue
    e=rom[0x4907+idx[m]*64:0x4907+idx[m]*64+64]
    ref=crt[n*25:n*25+25]
    assert ref==e[10:35] and gen[n*4]==e[9], hex(m)
    snap=[gen[n*4],gen[n*4+1],3]+list(e[5:9])+list(ref)+list(e[35:55])+[0]+list(e[55:64])
    assert len(snap)==62
    ds=dst[n*64+4:n*64+0x33]
    assert ds[0]==m
    t,ln,hz=info[m]
    out.append('  db 0x%02x,%d,%d ; mode, memtype, hz'%(m,t,hz))
    out.append('  dw %d'%(ln&0xFFFF))   # 65536 (mode 13h, whole window) is stored as 0
    out.append('  db '+','.join('0x%02x'%b for b in snap))
    out.append('  db '+','.join('0x%02x'%b for b in ds))
# entry size = 3+2+62+47 = 114
# VESA -> S3 internal mode mapping from the ROM (0xE37 list, 0xEA5 3-byte entries)
L=[];i=0xe37
while True:
    v=rom[i]|rom[i+1]<<8; i+=2
    if v==0xffff: break
    L.append(v)
out.append('NMAP equ %d'%len(L))
out.append('s3map:')
for k,v in enumerate(L):
    out.append('  dw 0x%03x'%v+'\n  db 0x%02x'%rom[0xea5+3*k])
open('vgaref.inc','w').write('\n'.join(out)+'\n')
print(len(L),'mapped modes')
